window.PASSWORD_CONFIG = {

  // 锁上面的标题
  title: '请输入解锁密码',

  // 小字提示，可以留空 ''
  hint: '提示：一个 4 位数字（月月日日）',

  // 密码位数（决定几个小圆点、键盘最多能按几下）
  length: 4,

  // ---------- 默认答案（示范用，请改成你自己的）----------
  answer: '1020',

  // ---------- 判断密码对不对 ----------
  verify(input) {
    // 【写法 1 · 直接比字符串】最常用
    return input === this.answer;

    // 【写法 2 · 忽略大小写（密码是字母时好用）】
    // return input.toLowerCase() === this.answer.toLowerCase();

    // 【写法 3 · 想允许几种答案都算对】
    // return ['0824', '520', '1314'].includes(input);

    // 【写法 4 · 不是固定密码，而是一道计算题】
    //   例如：答案是 "9"（TA 的生日月份 8 + 日期 1 = 9）
    // return Number(input) === 8 + 1;

    // 【写法 5 · 日期型，比如"距离生日还有几天"】
    // return Number(input) === 0;
  },

  // 密码错误时显示的话（可以随机换着说）
  onWrong(input) {
    const words = [
      '密码不对哦，再想想～',
      '不是这个，提示都给你了呀',
      '错啦，再试一次？',
      '唔……好像差一点'
    ];
    return words[Math.floor(Math.random() * words.length)];
  }

};
